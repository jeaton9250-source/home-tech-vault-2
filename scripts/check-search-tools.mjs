import assert from 'node:assert/strict';
import {calculate,calendarDate,warrantyEnd} from '../lib/tool-math.ts';
const value=(kind,inputs,index=0)=>calculate(kind,Object.fromEntries(Object.entries(inputs).map(([k,v])=>[k,String(v)])))?.[index].value;
assert.equal(value('meeting',{people:6,minutes:30,rate:40,frequency:1,weeks:48}),120);
assert.equal(value('meeting',{people:6,minutes:30,rate:40,frequency:1,weeks:48},2),5760);
assert.equal(value('email',{emails:40,minutes:2,days:5,weeks:48},2),320);
assert.equal(value('capacity',{hours:8,meetings:120,admin:60,breaks:60,task:45},1),5);
assert.equal(value('capacity',{hours:8,meetings:500,admin:60,breaks:60,task:45},2),140);
assert.equal(value('capacity',{hours:8,meetings:0,admin:0,breaks:0,task:0}),undefined);
assert.equal(value('energy',{watts:1000,hours:1,days:30,rate:0.15}),4.5);
assert.equal(value('energy',{watts:1000,hours:1,days:30,rate:0.15},2),54.75);
assert.equal(value('savings',{cost:1500,saved:300,months:12}),100);
assert.equal(value('savings',{cost:1500,saved:2000,months:12}),0);
assert.equal(value('savings',{cost:1500,saved:300,months:0}),undefined);
assert.equal(value('savings',{cost:1500,saved:300,months:2.5}),undefined);
assert.equal(warrantyEnd('2024-01-31',1),'2024-02-29');
assert.equal(warrantyEnd('2024-02-29',12),'2025-02-28');
assert.equal(warrantyEnd('9999-12-31',1),null);
assert.equal(calendarDate('2026-02-30'),null);
assert.equal(calendarDate(''),null);
assert.equal(value('warranty',{start:'2026-01-15',asof:'2027-01-15',months:12},1),0);
assert.equal(value('meeting',{people:6,minutes:'',rate:40,frequency:1,weeks:48}),undefined);
console.log('Search-tool calculation checks passed.');
